import PDFDocument from 'pdfkit';

const TEAL = '#0f766e';
const INK = '#14211f';
const MUTED = '#5b6b67';

const money = (n, currency) => {
  try {
    return new Intl.NumberFormat(currency === 'INR' ? 'en-IN' : 'en-US', { style: 'currency', currency, maximumFractionDigits: 0 }).format(n || 0);
  } catch {
    return `${currency} ${Math.round(n || 0)}`;
  }
};

export function streamPlanPdf(plan, res) {
  const { input, analysis: a } = plan;
  const cur = input.currency || 'INR';
  const doc = new PDFDocument({ size: 'A4', margin: 50, info: { Title: a.title || 'Business plan' } });
  doc.pipe(res);

  const h2 = (t) => {
    doc.moveDown(0.9).font('Helvetica-Bold').fontSize(14).fillColor(TEAL).text(t);
    doc.moveTo(50, doc.y + 2).lineTo(545, doc.y + 2).strokeColor('#cfe0db').lineWidth(0.8).stroke();
    doc.moveDown(0.5).fillColor(INK);
  };
  const p = (t) => doc.font('Helvetica').fontSize(10.5).fillColor(INK).text(t || '-', { lineGap: 2 });
  const label = (k, v) => {
    doc.font('Helvetica-Bold').fontSize(10.5).fillColor(INK).text(`${k}: `, { continued: true });
    doc.font('Helvetica').text(String(v ?? '-'), { lineGap: 2 });
  };
  const bullets = (items) => (items || []).forEach((i) => doc.font('Helvetica').fontSize(10.5).fillColor(INK).text(`•  ${i}`, { indent: 8, lineGap: 2 }));

  // Header
  doc.font('Helvetica-Bold').fontSize(22).fillColor(INK).text(a.title || 'Business plan');
  doc.font('Helvetica').fontSize(10).fillColor(MUTED).text(`${input.category}  |  ${input.location}  |  Budget ${money(input.budget, cur)}  |  ${new Date(plan.createdAt).toLocaleDateString('en-GB')}`);
  doc.moveDown(0.8);
  doc.font('Helvetica-Bold').fontSize(28).fillColor('#b45309').text(`${a.feasibility.score}/100`, { continued: true });
  doc.font('Helvetica').fontSize(11).fillColor(MUTED).text(`   feasibility score. ${a.feasibility.verdict}`);

  h2('The idea');
  p(input.idea);
  doc.moveDown(0.4);
  label('Target customers', input.targetCustomers);
  doc.moveDown(0.4);
  p(a.summary);

  h2('Target market');
  p(a.targetMarket.overview);
  label('Market size', a.targetMarket.marketSize);
  label('Segments', a.targetMarket.segments.join(', '));
  doc.moveDown(0.3);
  bullets(a.targetMarket.trends);

  h2('Competitors');
  a.competitors.forEach((c) => {
    doc.font('Helvetica-Bold').fontSize(10.5).fillColor(INK).text(c.name);
    label('Strength', c.strength);
    label('Weakness', c.weakness);
    doc.moveDown(0.4);
  });

  h2('Pricing strategy');
  label('Model', a.pricingStrategy.model);
  label('Suggested price', a.pricingStrategy.suggestedPrice);
  p(a.pricingStrategy.rationale);

  h2('Investment');
  label('Estimated total', money(a.investment.total, cur));
  a.investment.breakdown.forEach((b) => bullets([`${b.item}: ${money(b.amount, cur)}`]));

  h2('Revenue and profit');
  const f = a.financials;
  label('Monthly revenue', money(f.monthlyRevenue, cur));
  label('Monthly expenses', money(f.monthlyExpenses, cur));
  label('Monthly profit', money(f.monthlyProfit, cur));
  label('Break-even', `${f.breakEvenMonths} months`);
  label('Year-one revenue', money(f.yearOneRevenue, cur));
  label('Year-one profit', money(f.yearOneProfit, cur));

  h2('Marketing strategy');
  p(a.marketing.summary);
  doc.moveDown(0.3);
  bullets(a.marketing.channels.map((c) => `${c.channel}: ${c.tactic}`));

  h2('Risks');
  a.risks.forEach((r) => {
    doc.font('Helvetica-Bold').fontSize(10.5).fillColor(INK).text(`${r.risk} (${r.severity})`);
    p(`Mitigation: ${r.mitigation}`);
    doc.moveDown(0.3);
  });

  h2('Growth opportunities');
  bullets(a.growth);

  h2('Feasibility');
  p(a.feasibility.reasoning);
  doc.moveDown(0.3);
  const b = a.feasibility.breakdown;
  label('Market', `${b.market}/100`);
  label('Financial', `${b.financial}/100`);
  label('Competition', `${b.competition}/100`);
  label('Execution', `${b.execution}/100`);

  h2('Recommendations');
  bullets(a.recommendations);

  doc.moveDown(1.5).font('Helvetica-Oblique').fontSize(8.5).fillColor(MUTED)
    .text('Generated by StartupPlanner. AI-generated estimates are a starting point, not financial advice. Verify figures with local research before investing.');
  doc.end();
}
